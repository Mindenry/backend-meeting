UNION ALL SELECT 'drive_entries', COUNT(*) FROM "DriveEntry"
UNION ALL SELECT 'reminders', COUNT(*) FROM "Reminder"
UNION ALL SELECT 'wiki_articles', COUNT(*) FROM "WikiArticle"
