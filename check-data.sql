UNION ALL SELECT 'tasks', COUNT(*) FROM "Task"
UNION ALL SELECT 'meetings', COUNT(*) FROM "Meeting"
UNION ALL SELECT 'meeting_participants', COUNT(*) FROM "MeetingParticipant"
UNION ALL SELECT 'channels', COUNT(*) FROM "Channel"
UNION ALL SELECT 'messages', COUNT(*) FROM "Message"
UNION ALL SELECT 'direct_messages', COUNT(*) FROM "DirectMessage"
UNION ALL SELECT 'threads', COUNT(*) FROM "Thread"
UNION ALL SELECT 'message_reads', COUNT(*) FROM "MessageRead"
UNION ALL SELECT 'message_reactions', COUNT(*) FROM "MessageReaction"
UNION ALL SELECT 'task_comments', COUNT(*) FROM "TaskComment"
UNION ALL SELECT 'subtasks', COUNT(*) FROM "Subtask"
UNION ALL SELECT 'task_activity_logs', COUNT(*) FROM "TaskActivityLog"
UNION ALL SELECT 'time_entries', COUNT(*) FROM "TimeEntry"
UNION ALL SELECT 'work_hours', COUNT(*) FROM "WorkHours"
UNION ALL SELECT 'notifications', COUNT(*) FROM "Notification"
UNION ALL SELECT 'notification_preferences', COUNT(*) FROM "NotificationPreference"
UNION ALL SELECT 'announcements', COUNT(*) FROM "Announcement"
UNION ALL SELECT 'announcement_reads', COUNT(*) FROM "AnnouncementRead"
UNION ALL SELECT 'projects', COUNT(*) FROM "Project"
UNION ALL SELECT 'sprints', COUNT(*) FROM "Sprint"
UNION ALL SELECT 'epics', COUNT(*) FROM "Epic"
UNION ALL SELECT 'holidays', COUNT(*) FROM "Holiday"
UNION ALL SELECT 'audit_logs', COUNT(*) FROM "AuditLog"
UNION ALL SELECT 'role_permissions', COUNT(*) FROM "RolePermission"
UNION ALL SELECT 'invites', COUNT(*) FROM "Invite"
UNION ALL SELECT 'refresh_tokens', COUNT(*) FROM "RefreshToken"
UNION ALL SELECT 'documents', COUNT(*) FROM "Document"
